import React, { useState } from "react";
import { tryOn, img } from "../api.js";

export default function TryOn({ go, profileId, hasPhoto, product }) {
  const [res, setRes] = useState(null);
  const [busy, setBusy] = useState(false);
  const [err, setErr] = useState("");
  if (!product) return <section className="card narrow"><p>Pick a garment from the catalog first.</p><button className="primary" onClick={() => go("catalog")}>Open catalog</button></section>;

  const run = async () => {
    setBusy(true); setErr(""); setRes(null);
    try { setRes(await tryOn(profileId, product.id)); } catch (e) { setErr(e.message); } finally { setBusy(false); }
  };
  return (
    <section className="card">
      <h2>Virtual Try-On</h2>
      <div className="compare">
        <figure><img src={img(product.image)} alt={product.name} /><figcaption>{product.name}</figcaption></figure>
        <figure>{res ? <img src={img(res.url)} alt="try-on result" /> : <div className="ph">{busy ? "Generating… this can take 1–4 minutes on free servers" : "Your result appears here"}</div>}
          <figcaption>{res ? `Generated by ${res.backend}` : "AI preview"}</figcaption></figure>
      </div>
      {!hasPhoto && <div className="banner err">Try-on needs a photo. Go to Analyze and upload one.</div>}
      {err && <div className="banner err">{err}</div>}
      <p className="hint">💡 <strong>Pose Guideline:</strong> For the cleanest try-on without ghost/extra arms, use a photo standing straight with arms naturally resting at your sides (not folded across the chest).</p>
      <div className="row">
        <button className="primary" disabled={busy || !hasPhoto} onClick={run}>{busy ? "Working…" : res ? "Regenerate" : "Generate try-on"}</button>
        <button onClick={() => go("stylist", product)}>Ask the stylist</button>
        <button onClick={() => go("catalog")}>Back to catalog</button>
      </div>
    </section>
  );
}
